"""Write an erbdf checkpoint (48 kHz, n_fft 960) into mic thingy's C weights (src/dsp/erbdf_weights.c) and the golden
test data (tests/erbdf_golden.h). The C engine is src/dsp/erbdf.c; the "nn" effect picks it with `set nn model 1`.

    python export_erbdf_c.py runs/erbdf48k/best.pt

Golden data: the torch STFT of a deterministic signal (480 zeros first, like the C effect's start), the model run frame
by frame through step() from a zero state (the streaming path), for every frame the input spectrum X and the output
spectrum Y over all 481 bins plus the voice probability. tests/test_fx.c feeds X into the C engine and compares.
"""
import argparse
import os

import numpy as np
import torch

from se import checkpoint

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "src", "dsp", "erbdf_weights.c")
GOLDEN = os.path.join(HERE, "..", "tests", "erbdf_golden.h")


def arr(name, t):
    a = t.detach().cpu().numpy().astype(np.float32).ravel()
    lines = ["    " + ",".join(f"{v:.8g}" for v in a[i:i + 8]) + "," for i in range(0, len(a), 8)]
    return f"static const float {name}[{len(a)}] = {{\n" + "\n".join(lines) + "\n};\n"


def golden_signal(n):
    i = np.arange(n, dtype=np.float64)
    x = 0.3 * np.sin(2 * np.pi * 440 * i / 48000) + 0.1 * np.sin(2 * np.pi * 3150 * i / 48000) * ((i % 4800) < 2400) \
        + 0.02 * ((i * 7919 % 1000) / 1000.0 - 0.5)
    return x.astype(np.float32)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("ckpt")
    ap.add_argument("--src", default=SRC)
    ap.add_argument("--golden", default=GOLDEN)
    a = ap.parse_args()
    m, cfg, stft, _ = checkpoint.load(a.ckpt)
    if cfg.model.name != "erbdf" or cfg.data.sample_rate != 48000 or cfg.stft.n_fft != 960 or cfg.stft.window != "vorbis":
        raise SystemExit("the C engine runs erbdf at 48 kHz with 960-sample Vorbis frames")
    if not m.D:
        raise SystemExit("export needs the deep-filter branch (df_order >= 2)")
    m.eval()
    sd = m.state_dict()
    V, nb, h, C, D, order = m.speech_bins, m.nb, m.h, m.C, m.D, m.order
    na = (nb - 1) // 2 + 1
    names = [  # (C field, state_dict key)
        ("erb_fwd", "erb_fwd"), ("erb_inv", "erb_inv"), ("mean", "mean"), ("std_", "std"),
        ("ea1_w", "enc_a.0.weight"), ("ea1_b", "enc_a.0.bias"), ("ea2_w", "enc_a.2.weight"), ("ea2_b", "enc_a.2.bias"),
        ("la_w", "lin_a.weight"), ("la_b", "lin_a.bias"),
        ("g_wih", "gru.weight_ih_l0"), ("g_whh", "gru.weight_hh_l0"), ("g_bih", "gru.bias_ih_l0"), ("g_bhh", "gru.bias_hh_l0"),
        ("oe_w", "out_erb.weight"), ("oe_b", "out_erb.bias"), ("ov_w", "out_vad.weight"), ("ov_b", "out_vad.bias"),
        ("eb1_w", "enc_b1.0.weight"), ("eb1_b", "enc_b1.0.bias"), ("eb2_w", "enc_b2.0.weight"), ("eb2_b", "enc_b2.0.bias"),
        ("lb_w", "lin_b.weight"), ("lb_b", "lin_b.bias"),
        ("gd_wih", "gru_df.weight_ih_l0"), ("gd_whh", "gru_df.weight_hh_l0"), ("gd_bih", "gru_df.bias_ih_l0"),
        ("gd_bhh", "gru_df.bias_hh_l0"),
        ("ld_w", "lin_df.weight"), ("ld_b", "lin_df.bias"), ("u1_w", "up1.weight"), ("u1_b", "up1.bias"),
        ("u2_w", "up2.weight"), ("u2_b", "up2.bias"),
    ]
    parts = [
        "/* Generated by ml/export_erbdf_c.py from an erbdf checkpoint (ml/se/models/erbdf.py) - do not edit.\n"
        f" * {sum(p.numel() for p in m.parameters())} parameters, hidden {h}, {nb} ERB bands over {V} bins, deep filter on {D} bins,\n"
        f" * {order} taps, {C} conv channels. Weights are row-major as torch stores them (ConvTranspose1d: [in][out][k]).\n"
        " * Training speech: LibriSpeech (CC BY 4.0, openslr.org/12); noise: DEMAND-style, RIRS_NOISES and synthesised. */\n",
        '#include "dsp/erbdf.h"\n\n',
    ]
    for cname, key in names:
        parts.append(arr(cname, sd[key]))
    fields = ", ".join(c for c, _ in names)
    parts.append(f"\nconst VfErbDfWeights vf_erbdf_default = {{ {V}, {nb}, {h}, {C}, {D}, {order}, {m.hf_lo}, {m.hf_hi}, "
                 f"{float(m.compress)!r}f,\n    {fields} }};\n")
    with open(a.src, "w", newline="\n") as f:
        f.write("".join(parts))

    frames = 24
    x = golden_signal(frames * 480)
    xp = torch.from_numpy(np.concatenate([np.zeros(480, np.float32), x]))[None]
    with torch.no_grad():
        X = stft(xp)[0]                                          # [481, T] complex
        T = X.shape[1]
        state = m.init_state(1)
        ys, vs = [], []
        for t in range(T):
            y, state, v = m.step(X[:, t][None], state)
            ys.append(y[0])
            vs.append(v[0])
        Y = torch.stack(ys, 1)
        vad = torch.stack(vs)
        Xf = torch.stack([X.real, X.imag], -1).permute(1, 0, 2).contiguous()      # [T, 481, 2]
        Yf = torch.stack([Y.real, Y.imag], -1).permute(1, 0, 2).contiguous()
    with open(a.golden, "w", newline="\n") as f:
        f.write("/* Generated by ml/export_erbdf_c.py together with src/dsp/erbdf_weights.c - do not edit.\n"
                " * X, Y: [frame][bin 0..480][re, im] of the torch STFT of the golden signal and of the streaming model output. */\n")
        f.write(f"#define ERBDF_GOLDEN_FRAMES {T}\n#define ERBDF_GOLDEN_BINS {X.shape[0]}\n")
        f.write(arr("erbdf_golden_x", Xf))
        f.write(arr("erbdf_golden_y", Yf))
        f.write(arr("erbdf_golden_vad", vad))
    print(f"wrote {a.src} ({os.path.getsize(a.src) // 1024} KB) and {a.golden}: V={V} nb={nb} h={h} C={C} D={D} order={order} "
          f"na={na} hf={m.hf_lo}..{m.hf_hi} compress={float(m.compress)} frames={T}")


if __name__ == "__main__":
    main()
