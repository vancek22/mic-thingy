"""Export a trained checkpoint to C.

    python export.py <ckpt.pt> [--src ../../src/dsp/nn_weights.c] [--golden ../../tests/nn_golden.h]

nn_weights.c holds the float32 weights (row-major, as torch stores them) and `vf_nn_default`.
nn_golden.h holds a deterministic test signal's features, gains and voice probabilities computed by torch;
tests/test_fx.c checks that the C inference reproduces them.
"""
import argparse
import os

import numpy as np
import torch

import nnlib as L

HERE = os.path.dirname(os.path.abspath(__file__))


def arr(name, t):
    a = t.detach().cpu().numpy().astype(np.float32).ravel()
    lines = []
    for i in range(0, len(a), 8):
        lines.append("    " + ",".join(f"{v:.8g}" for v in a[i:i + 8]) + ",")
    return f"static const float {name}[{len(a)}] = {{\n" + "\n".join(lines) + "\n};\n"


def golden_signal(n):
    i = np.arange(n, dtype=np.float64)
    x = 0.3 * np.sin(2 * np.pi * 440 * i / 48000) + 0.1 * np.sin(2 * np.pi * 3150 * i / 48000) * ((i % 4800) < 2400) \
        + 0.02 * ((i * 7919 % 1000) / 1000.0 - 0.5)
    return x.astype(np.float32)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("ckpt")
    ap.add_argument("--src", default=os.path.join(HERE, "..", "..", "src", "dsp", "nn_weights.c"))
    ap.add_argument("--golden", default=os.path.join(HERE, "..", "..", "tests", "nn_golden.h"))
    a = ap.parse_args()
    ck = torch.load(a.ckpt)
    m = L.Denoiser(ck["hidden"])
    m.load_state_dict(ck["model"])
    m.eval()
    H = ck["hidden"]
    sd = m.state_dict()
    parts = [
        "/* Generated by tools/nn/export.py from a checkpoint trained with tools/nn/train.py - do not edit.\n"
        f" * hidden {H}, step {ck.get('step')}, {sum(p.numel() for p in m.parameters())} parameters.\n"
        " * Training speech: LibriSpeech (CC BY 4.0, openslr.org/12); noise: synthesised (tools/nn/nnlib.py). */\n",
        '#include "dsp/nn.h"\n\n',
        arr("mean", sd["mean"]), arr("std_", sd["std"]),
        arr("in_w", sd["inp.weight"]), arr("in_b", sd["inp.bias"]),
        arr("g1_wih", sd["g1.weight_ih_l0"]), arr("g1_whh", sd["g1.weight_hh_l0"]),
        arr("g1_bih", sd["g1.bias_ih_l0"]), arr("g1_bhh", sd["g1.bias_hh_l0"]),
        arr("g2_wih", sd["g2.weight_ih_l0"]), arr("g2_whh", sd["g2.weight_hh_l0"]),
        arr("g2_bih", sd["g2.bias_ih_l0"]), arr("g2_bhh", sd["g2.bias_hh_l0"]),
        arr("out_w", sd["out.weight"]), arr("out_b", sd["out.bias"]),
        f"\nconst VfNnWeights vf_nn_default = {{ {L.NB}, {H}, mean, std_, in_w, in_b,\n"
        "    g1_wih, g1_whh, g1_bih, g1_bhh, g2_wih, g2_whh, g2_bih, g2_bhh, out_w, out_b };\n",
    ]
    with open(a.src, "w", newline="\n") as f:
        f.write("".join(parts))

    # golden data: the C effect starts with a zero first half-frame, so prepend 480 zeros
    frames = 24
    x = golden_signal(frames * L.HOP)
    xp = torch.from_numpy(np.concatenate([np.zeros(L.HOP, np.float32), x]))[None]
    with torch.no_grad():
        feat = L.features(L.stft(xp))               # [1, F, NB]
        g, v = m(feat)
    F = feat.shape[1]
    with open(a.golden, "w", newline="\n") as f:
        f.write("/* Generated by tools/nn/export.py together with src/dsp/nn_weights.c - do not edit. */\n")
        f.write(f"#define NN_GOLDEN_FRAMES {F}\n")
        f.write(arr("nn_golden_feat", feat[0]))
        f.write(arr("nn_golden_gain", g[0]))
        f.write(arr("nn_golden_vad", torch.sigmoid(v[0])))
    print(f"wrote {a.src} ({os.path.getsize(a.src) // 1024} KB) and {a.golden}, {F} golden frames")


if __name__ == "__main__":
    main()
